    if not models:
        raise ValueError("No models found in data")

    palettes = sns.color_palette("colorblind", n_colors=len(models))
    model_colors = dict(zip(PREFERRED_MODELS, palettes))

    fig, ax = plt.subplots(1, 1, figsize=(10, 7))

    # Prepare and plot grouped bars
