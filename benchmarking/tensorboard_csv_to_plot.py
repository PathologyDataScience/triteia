def parse_args():
    parser = argparse.ArgumentParser(description="Plot tensorboard data")
    parser.add_argument(
        "--output-dir",
        type=str,
        help="output directory for plot files",
        default="./plot_out",
    )

    args = parser.parse_args()

    if not os.path.exists(args.output_dir):
        os.makedirs(args.output_dir)

    return args


def _filter_by_plot_key(df: pd.DataFrame, plot_key: str) -> pd.DataFrame:
    """Filter DataFrame to rows matching plot_key (if column exists)."""
    if "plot_key" in df.columns:
        df = df[df["plot_key"] == plot_key].copy()
    return df


def _validate_required_cols(df: pd.DataFrame, required_cols: set, caller: str = ""):
    """Raise KeyError if any required columns are missing."""
    missing = sorted(required_cols - set(df.columns))
    if missing:
        raise KeyError(
            f"{caller} expected columns {sorted(required_cols)} "
            f"but is missing {missing}. "
            f"Available columns: {sorted(df.columns.tolist())}"
        )


def _coerce_numeric(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    """Convert columns to numeric, coercing errors."""
    df = df.copy()
    for col in cols:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def _clean_model_names(series: pd.Series) -> pd.Series:
    """Strip framework/variant prefixes from model name column."""
    return (
        series.str.replace("triton", "")
        .str.replace("pytorch", "")
        .str.replace("inferenceonly", "")
    )


def _available_models(df: pd.DataFrame) -> list[str]:
    """Return the subset of PREFERRED_MODELS present in df['model']."""
    return [m for m in PREFERRED_MODELS if m in df["model"].unique()]


def _prepare_df(
    df: pd.DataFrame,
    plot_key: str,
    required_cols: set,
    numeric_cols: list[str],
    dropna_cols: list[str],
    caller: str = "",
    clean_models: bool = False,
) -> pd.DataFrame:
    """Common pipeline: filter → validate → coerce → dropna → (optional) clean names."""
    df = _filter_by_plot_key(df, plot_key)
    if df.empty:
        raise ValueError(f"No data available to plot for plot key '{plot_key}'")
    _validate_required_cols(df, required_cols, caller)
    df = _coerce_numeric(df, numeric_cols)
    df = df.dropna(subset=dropna_cols)
    if clean_models and "model" in df.columns:
        df["model"] = _clean_model_names(df["model"])
    return df


def _create_model_subplots(
    models, *, n_rows=1, col_width=5, row_height=6, **subplot_kw
):
    """Create a figure with one column per model, handling the single-model edge case."""
    n_cols = len(models)
    fig, axes = plt.subplots(
        n_rows,
        n_cols,
        figsize=(col_width * n_cols, row_height * n_rows),
        gridspec_kw={"hspace": 0.5},
        **subplot_kw,
    )
    # Normalise axes to always be indexable
    if n_rows == 1 and n_cols == 1:
        axes = [axes]
    elif n_rows == 1:
        axes = list(axes)
    elif n_cols == 1:
        import numpy as _np

        axes = axes.reshape(n_rows, 1)
    return fig, axes


def _build_gpu_groups(model_data, category_values, value_col, category_col):
    """Build {gpu: {category_value: throughput}} lookup from model_data."""
    gpu_groups = {}
    for gpu in ALLOWED_GPU_TICKS:
        gpu_groups[gpu] = {}
        for cat in category_values:
            mask = (model_data["gpus"] == gpu) & (model_data[category_col] == cat)
            gpu_groups[gpu][cat] = (
                float(model_data.loc[mask, value_col].iloc[0]) if mask.any() else 0
            )
    return gpu_groups


def _plot_overlapping_bars(
    ax, gpu_groups, category_values, color_map, bar_width=0.6, alpha_map=None
):
    """Draw overlapping bars on *ax* (highest behind, lowest in front)."""
    for gpu_idx, gpu in enumerate(ALLOWED_GPU_TICKS):
        pairs = [(cat, gpu_groups[gpu][cat]) for cat in category_values]
        pairs_sorted = sorted(pairs, key=lambda p: p[1], reverse=True)
        for cat, height in pairs_sorted:
            if height > 0:
                kw = dict(
                    color=color_map.get(cat, "gray"),
                    edgecolor="black",
                    linewidth=0.5,
                )
                if alpha_map:
                    kw["alpha"] = alpha_map.get(cat, 0.5)
                ax.bar(gpu_idx, height, bar_width, **kw)


def _plot_grouped_bars(
    ax, gpu_groups, category_values, color_map, bar_width=None, alpha_map=None
):
    """Draw side-by-side (grouped) bars on *ax*, one sub-bar per category value."""
    n_cats = len(category_values)
    if bar_width is None:
        bar_width = 0.8 / max(n_cats, 1)

    for gpu_idx, gpu in enumerate(ALLOWED_GPU_TICKS):
        for cat_idx, cat in enumerate(category_values):
            offset = (cat_idx - (n_cats - 1) / 2) * bar_width
            height = gpu_groups[gpu][cat]
            if height > 0:
                kw = dict(
                    color=color_map.get(cat, "gray"),
                    edgecolor="black",
                    linewidth=0.5,
                )
                if alpha_map:
                    kw["alpha"] = alpha_map.get(cat, 0.5)
                ax.bar(gpu_idx + offset, height, bar_width, **kw)


def _format_gpu_axis(ax, ax_idx, *, ylabel="tiles / s", ylim_max=None, fontsize=14):
    """Apply common GPU-axis formatting."""
    x = range(len(ALLOWED_GPU_TICKS))
    ax.set_xlabel("GPUs", fontsize=fontsize)
    if ax_idx == 0:
        ax.set_ylabel(ylabel, fontsize=fontsize)
    ax.set_xticks(list(x))
    ax.set_xticklabels([str(g) for g in ALLOWED_GPU_TICKS], fontsize=fontsize - 1)
    ax.grid(True, alpha=0.3, axis="y")
    if ylim_max is not None:
        ax.set_ylim(0, ylim_max)


def _add_bottom_legend(fig, handles, ncol):
    """Place a shared legend below the figure."""
    fig.legend(
        handles=handles,
        loc="upper center",
        bbox_to_anchor=(0.5, -0.02),
        ncol=ncol,
        frameon=True,
    )


def _save_figure_formats(fig, plot_path, **savefig_kwargs):
    """Save figure as PNG plus a matching SVG file."""
    root, ext = os.path.splitext(plot_path)
    svg_path = f"{root}.svg" if ext else f"{plot_path}.svg"
    output_paths = [plot_path]
    if os.path.abspath(svg_path) != os.path.abspath(plot_path):
        output_paths.append(svg_path)

    for output_path in output_paths:
        fig.savefig(output_path, **savefig_kwargs)
        logging.info("Saved plot to %s", output_path)


def _save_and_close(fig, plot_path, suptitle=None, rect=None):
    """Set suptitle, tight_layout, save as PNG/SVG, log, close."""
    if suptitle:
        fig.suptitle(suptitle, fontsize=16, fontweight="bold", y=0.98)
    plt.tight_layout(rect=rect or [0, 0.03, 1, 0.96])
    _save_figure_formats(fig, plot_path, bbox_inches="tight", dpi=300)
    plt.close()


def _make_rect_handles(values, color_map, label_fmt="{}", alpha_map=None):
    """Build a list of Rectangle legend handles."""
    handles = []
    for val in values:
        kw = dict(
            facecolor=color_map.get(val, "gray"),
            edgecolor="black",
            label=label_fmt.format(val),
        )
        if alpha_map:
            kw["alpha"] = alpha_map.get(val, 0.5)
        handles.append(plt.Rectangle((0, 0), 1, 1, **kw))
    return handles


