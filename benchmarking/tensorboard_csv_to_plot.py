    if df.empty:
        raise ValueError(f"No data available to plot for plot key '{plot_key}'")

    # Determine throughput column name
    if "throughput_mean" in df.columns:
        throughput_col = "throughput_mean"
    elif "throughput_agg_mean" in df.columns:
        throughput_col = "throughput_agg_mean"
